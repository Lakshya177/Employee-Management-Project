    private void btnsSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsSearchActionPerformed
        // TODO add your handling code here:

        String searchId = txtSearch.getText();

        if (searchId.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter Employee ID");
            return;
        }

        try {
            // 1. Load MySQL Driver
            Class.forName("com.mysql.cj.jdbc.Driver");

            // 2. Connect to database
            java.sql.Connection con = java.sql.DriverManager.getConnection(
                    "jdbc:mysql://localhost:3306/employee_db", "root", "root");

            // 3. Prepare SQL query
            // Replace 'employee' with your actual table name
            // Replace 'id' with your actual ID column name
            String sql = "SELECT * FROM employee_db WHERE emp_id = ?";
            java.sql.PreparedStatement pst = con.prepareStatement(sql);
            pst.setInt(1, Integer.parseInt(searchId)); // use Integer.parseInt if ID is int

            // 4. Execute query
            java.sql.ResultSet rs = pst.executeQuery();

            // 5. Get JTable model
            javax.swing.table.DefaultTableModel model
                    = (javax.swing.table.DefaultTableModel) tblEmployee.getModel();

            // 6. Clear previous table data
            model.setRowCount(0);

            // 7. Add result to table
            boolean found = false;
            while (rs.next()) {
                found = true;
                model.addRow(new Object[]{
                    rs.getString("empName"), // Column name for Employee Name
                    rs.getString("email"), // Column name for Email
                    rs.getString("mobile"), // Column name for Mobile
                    rs.getString("city") // Column name for City
                });
            }

            // 8. Show message if no record found
            if (!found) {
                javax.swing.JOptionPane.showMessageDialog(this, "No record found!");
            }

            // 9. Close connection
            con.close();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, e);
        }


    }//GEN-LAST:event_btnsSearchActionPerformed

