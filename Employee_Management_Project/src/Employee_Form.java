    private void btnRefreshActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRefreshActionPerformed
        // TODO add your handling code here:
     try {
    Connection con = DriverManager.getConnection(
        "jdbc:mysql://localhost:3306/employee_db", "root", "root"
    );
    Statement st = con.createStatement();

    // Step 1: Initialize variable
    st.execute("SET @num := 0");

    // Step 2: Resequence emp_id
    st.executeUpdate("UPDATE employee_db SET emp_id = (@num := @num + 1) ORDER BY emp_id");

    // Step 3: Get the current maximum emp_id
    ResultSet rs = st.executeQuery("SELECT MAX(emp_id) FROM employee_db");
    int nextId = 1;
    if (rs.next()) {
        nextId = rs.getInt(1) + 1; // next AUTO_INCREMENT value
    }
    rs.close();

    // Step 4: Reset AUTO_INCREMENT
    st.execute("ALTER TABLE employee_db AUTO_INCREMENT = " + nextId);

    st.close();
    con.close();

    JOptionPane.showMessageDialog(null, "Employee IDs resequenced successfully!");

} catch (Exception e) {
    JOptionPane.showMessageDialog(null, e.getMessage());
}


    }//GEN-LAST:event_btnRefreshActionPerformed

